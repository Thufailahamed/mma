import { pbkdf2Sync, randomBytes, randomUUID } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ENVIRONMENT = process.env.ENVIRONMENT ?? 'development'

// The production database stays empty. This guard is the control, not a
// convention, so it exits non-zero rather than warning.
if (ENVIRONMENT === 'production') {
  console.error('Refusing to seed an admin user in production.')
  process.exit(1)
}

const email = process.env.SEED_ADMIN_EMAIL
const password = process.env.SEED_ADMIN_PASSWORD
if (!email || !password) {
  console.error('SEED_ADMIN_EMAIL and SEED_ADMIN_PASSWORD must be set.')
  console.error('Load them with: set -a; source apps/api/.dev.vars; set +a')
  process.exit(1)
}
if (password.length < 12) {
  console.error('SEED_ADMIN_PASSWORD must be at least 12 characters.')
  process.exit(1)
}

// Identical format and iteration count to the Worker's WebCrypto implementation
// in apps/api/src/crypto/password.ts, so a seeded admin logs in through the
// real login path.
const ITERATIONS = 310_000
const salt = randomBytes(16)
const derived = pbkdf2Sync(password, salt, ITERATIONS, 32, 'sha256')
const hash = `pbkdf2_sha256$${ITERATIONS}$${salt.toString('base64')}$${derived.toString('base64')}`

const userId = randomUUID()
const profileId = randomUUID()
const now = Date.now()
const literal = (value) => `'${String(value).replaceAll("'", "''")}'`

const sql = `-- Generated by scripts/seed-admin.mjs. Do not edit by hand.
INSERT INTO users (id, email, username, display_name, password_hash, role, xp, level, created_at, updated_at) VALUES (
  ${literal(userId)}, ${literal(email)}, 'admin', 'Administrator',
  ${literal(hash)}, 'ADMIN', 0, 1, ${now}, ${now}
);
INSERT INTO user_profiles (id, user_id, created_at, updated_at) VALUES (
  ${literal(profileId)}, ${literal(userId)}, ${now}, ${now}
);
`

const outPath = resolve(ROOT, 'database/seed/0002_admin.sql')
writeFileSync(outPath, sql)
console.log(`Wrote ${outPath}`)
